import {test,expect} from '@playwright/test';
test('conversation and a scoped graph: history stays folded, changes fork, explanations do not; dialog and zoom remain usable',async({page,request})=>{
 const data=await(await request.post('/api/spaces/demo/housing')).json();
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/#'+data.id);
 await expect(page.locator('[data-tree-node]')).toHaveCount(1);
 await page.locator('.prompt-history').click();
 const chat=page.locator('#conversation-message');
 await chat.fill('如果月租改为5000元呢？');await chat.press('Enter');
 await expect(page.locator('.chat-message.user')).toHaveCount(1);
 await expect(page.locator('[data-tree-node]')).toHaveCount(2);
 expect(await page.locator('.flow-edges g path').count()).toBeGreaterThan(3);
 await expect(page.locator('.tree-origin .board-limits')).toContainText('4,000');
 await expect(page.locator('.tree-branch > .tree-candidates > button')).toHaveCount(3);
 await chat.fill('为什么还有一个房源被排除？');await chat.press('Enter');
 await expect(page.locator('.chat-message.user')).toHaveCount(2);
 await expect(page.locator('[data-tree-node]')).toHaveCount(2);
 await page.reload();await expect(page.locator('.chat-message.user')).toHaveCount(2);await page.locator('.prompt-history').click();
 await chat.fill('如果通勤改为60分钟呢？');await chat.press('Enter');
 await expect(page.locator('[data-tree-node]')).toHaveCount(3);
 expect(await page.locator('.flow-edges g path').count()).toBeGreaterThan(6);
 const third=page.locator('.flow-row').last();await expect(third.locator('.tree-branch > .tree-candidates > button')).toHaveCount(4);
 const column=await third.evaluate(el=>parseFloat(el.style.left)),parentColumn=await page.locator('.flow-row').first().evaluate(el=>parseFloat(el.style.left));expect(column).toBeGreaterThan(parentColumn);
 await page.getByRole('button',{name:'收起对话记录'}).click();await page.locator('.flow-row').first().locator('[data-tree-condition]').click();await page.getByRole('button',{name:'收起这条分支'}).click();
 await expect(page.locator('[data-tree-node]')).toHaveCount(1);
 await expect(page.locator('.chat-message.user')).toHaveCount(3);
 await page.locator('.flow-history summary').click();await page.locator('[data-show-branch]').last().click();
 await expect(page.locator('[data-tree-node]')).toHaveCount(3);
 await page.getByRole('button',{name:'适应画布',exact:true}).click();
 await third.locator('.tree-choice').first().click();await expect(page.getByRole('dialog',{name:'方案详情'})).toBeVisible();
 await page.keyboard.press('Escape');await expect(page.locator('.option-dialog')).toHaveCount(0);
 await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
 expect(errors).toEqual([]);
});
test('old branches are available on demand instead of filling the initial canvas',async({page,request})=>{
 const data=await(await request.post('/api/spaces/demo/housing')).json();
 const scenarios=[...data.scenarios,...[3500,4500,5000].map((price,i)=>({id:'branch-'+i,name:'monthly '+price,settings:{...data.settings,limits:{...data.settings.limits,price}},parentScenarioId:'scenario-baseline'}))];
 const saved=await(await request.post('/api/spaces/'+data.id+'/versions',{data:{adaptive:true,scenarios,activeScenarioId:'branch-2'}})).json();
 await page.goto('/#'+saved.id);await expect(page.locator('[data-tree-node]')).toHaveCount(2);
 await page.locator('.flow-history summary').click();await page.locator('[data-show-branch="branch-0"]').click();await expect(page.locator('[data-tree-node]')).toHaveCount(3);
 await page.getByRole('button',{name:'新分支',exact:false}).click();await expect(page.locator('[data-tree-node]')).toHaveCount(3);
 await expect(page.locator('#conversation-message')).toHaveValue('如果');
});
