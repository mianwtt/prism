import {test,expect} from '@playwright/test';
import {completeFixture} from './complete-space.fixture.mjs';
test('complete records form an interactive decision space with an actual flip and quote-level evidence',async({page,request})=>{
 const created=await(await request.post('/api/spaces/demo')).json();
 const space={...created,...completeFixture()};
 await page.route('**/api/spaces/'+space.id,route=>route.fulfill({json:space}));
 await page.route('https://example.com/fixture-product-*.svg',route=>route.fulfill({contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="400" height="260"><rect x="60" y="40" width="280" height="160" rx="8" fill="#dce7cb" stroke="#527b60"/><path d="M40 220h320" stroke="#527b60" stroke-width="8"/></svg>'}));
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/classic#'+space.id);
 await page.locator('.candidate-shelf > summary').click();
 await page.locator('.decision-reasoning > summary').click();
 await expect(page.locator('.product-canonical')).toHaveCount(2);
 await expect(page.locator('.canvas-products')).not.toContainText('待补充');
 await expect(page.locator('#decision-insight h3')).toContainText('惠普');
 await expect(page.locator('.product-price').first()).toContainText('¥5,199');
 await page.locator('.scenario-switches [data-select-scenario="scenario-budget"]').click();
 await expect(page.locator('#decision-insight .decision-flipped')).toBeVisible();
 await expect(page.locator('.product-winner h4')).toContainText('联想');
 await expect(page.locator('[data-product-id="hp-fixture"] .product-change')).toHaveText('已退出');
 await page.locator('#decision-insight [data-budget="5199"]').click();
 await expect(page.locator('.product-winner h4')).toContainText('惠普');
 await expect(page.locator('#budget')).toHaveValue('5199');
 await page.locator('.product-winner .product-price').click();
 await expect(page.locator('#evidence-body blockquote').first()).toContainText('¥5199.00');
 await page.getByRole('button',{name:'关闭证据窗口'}).click();
 await page.locator('.product-winner [data-product-sources]').click();
 await expect(page.locator('#specification-comparison tbody tr')).toHaveCount(7);
 await page.locator('.specification-details > summary').click();
 await page.locator('#specification-comparison [data-detail-key="cpu"]').first().click();
 await expect(page.locator('#evidence-body blockquote')).toContainText('CPU型号Core 5 210H');
 await page.getByRole('button',{name:'关闭证据窗口'}).click();
 await page.getByRole('button',{name:'情景推演',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
 await page.locator('.scenario-switches [data-select-scenario="scenario-commute"]').click();
 await expect(page.locator('.product-winner h4')).toContainText('惠普');
 expect(errors).toEqual([]);
});
test('new incomplete research stays a draft instead of rendering placeholder comparison cards',async({page,request})=>{
 const space=await(await request.post('/api/spaces/demo')).json();
 space.mode='live';
 space.comparisonData={comparisonReady:[],researchDrafts:[{name:'Incomplete test fixture',blockers:['missing:priceCNY']}]};
 await page.route('**/api/spaces/'+space.id,route=>route.fulfill({json:space}));
 await page.goto('/classic#'+space.id);
 await expect(page.locator('.collection-incomplete')).toBeVisible();
 await expect(page.locator('.collection-incomplete')).toContainText('未取得页面价格');
 await expect(page.locator('.canvas-product')).toHaveCount(0);
 await page.getByRole('button',{name:'查看采集记录 →',exact:true}).click();
 await expect(page.locator('#research-pane')).toBeVisible();
});
