import {test,expect} from '@playwright/test';
import {readFile} from 'node:fs/promises';

test('task intake restores structured drafts and sends the actual combined brief',async({page})=>{
  await page.goto('/');
  await expect(page.locator('#research-button>span')).toBeVisible();
  await page.locator('#question').fill('比较适合远程工作的几个城市');
  await page.locator('.task-intake-details>summary').click();
  await page.locator('#task-constraints').fill('月生活预算 6000 元，不考虑长期驾车');
  await page.locator('#task-preferences').fill('更看重公共交通和安静的工作环境');
  await page.locator('#task-outcome').fill('三项候选及决定前的核对清单');
  await page.reload();
  await expect(page.locator('#task-constraints')).toHaveValue(/6000/);
  await expect(page.locator('#question')).toHaveValue('比较适合远程工作的几个城市');
  await page.route('**/api/settings',route=>route.fulfill({json:{ready:true}}));
  let brief;
  await page.route('**/api/research',route=>{brief=route.request().postDataJSON();return route.fulfill({status:503,json:{error:'受控服务不可用'}});});
  await page.locator('#research-button').click();
  await expect.poll(()=>brief?.question).toContain('三项候选');
  expect(brief.question).toContain('月生活预算 6000');
  await page.reload();
  await expect(page.locator('#task-preferences')).toHaveValue(/公共交通/);
});

test('canvas stays primary and branch changes flow into the downloadable decision brief',async({page})=>{
  await page.goto('/');
  await page.locator('#housing-demo-button').click();
  await expect(page.locator('.u-tabs button').first()).toHaveText('What-if 画布');
  await expect(page.locator('.tree-origin')).toBeVisible();
  const original=await page.locator('.tree-origin .tree-candidates').textContent();
  let researchCalls=0;
  page.on('request',request=>{if(request.method()==='POST'&&/research|explore|adapt/.test(request.url()))researchCalls++;});
  await page.locator('[data-live-input=price]').fill('3000');
  await page.locator('[data-live-input=price]').dispatchEvent('change');
  await expect(page.locator('.mission-strip')).toContainText('0 个符合条件');
  await expect(page.locator('.mission-branch-delta')).toContainText('2 个退出');
  expect(await page.locator('.tree-origin .tree-candidates').textContent()).toBe(original);
  await page.getByRole('button',{name:'查看当前建议书'}).click();
  await expect(page.locator('.mission-conditions')).toContainText('3,000');
  await expect(page.locator('.mission-next')).toContainText('没有匹配方案');
  const downloading=page.waitForEvent('download');
  await page.getByRole('button',{name:'导出决策建议书',exact:true}).click();
  const download=await downloading;
  const report=await readFile(await download.path(),'utf8');
  expect(report).toContain('3,000');
  expect(report).toContain('其中 0 个符合当前条件');
  expect(report).toContain('画布草稿，尚未另存');
  expect(report).toContain('与父分支的变化');
  expect(report).toContain('虚构演示');
  expect(report).toContain('尚未记录最终选择');
  expect(researchCalls).toBe(0);
  await page.getByRole('button',{name:'What-if 画布',exact:true}).click();
  await expect(page.locator('.tree-origin')).toBeVisible();
  await expect(page.locator('.mission-strip')).toContainText('0 个符合条件');
});

test('task overview links actual options, preserves notes across immutable versions and returns to evidence',async({page})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await page.locator('#housing-demo-button').click();
  await expect(page).toHaveURL(/#[a-f0-9-]+$/);
  const original=page.url();
  await page.getByRole('button',{name:'查看当前建议书'}).click();
  await expect(page.locator('.mission-question')).toContainText('杭州');
  await expect(page.locator('.proposal-recommendation')).toHaveCount(2);await expect(page.locator('.proposal-rejected article')).toHaveCount(2);
  await expect(page.locator('.mission-evidence')).toContainText('演示资料');
  await page.locator('#mission-note').fill('先核对采光和隔音，再决定是否预约看房。');
  await page.reload();
  await expect(page.locator('#mission-note')).toHaveValue(/隔音/);
  await page.getByRole('button',{name:'保存备忘',exact:true}).click();
  await expect.poll(()=>page.url()).not.toBe(original);
  await expect(page.locator('.mission-note')).toContainText('已随当前版本保存');
  await page.reload();
  await expect(page.locator('[data-u-pane=overview][aria-current=page]')).toBeVisible();
  await expect(page.locator('#mission-note')).toHaveValue(/隔音/);
  await page.locator('.proposal-rejected>summary').click();await page.locator('.proposal-rejected [data-mission-candidate]').first().click();
  await expect(page.locator('.evidence-workflow')).toBeVisible();
  await page.goto(original);
  await page.getByRole('button',{name:'决策建议书',exact:true}).click();
  await expect(page.locator('#mission-note')).toHaveValue('');
  expect(errors).toEqual([]);
});

test('overview and task start remain usable at mobile width without exposing execution internals',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await expect(page.locator('#research-button')).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
  await page.locator('#demo-button').click();
  await page.locator('.tree-toolbar [data-toggle-inspector]').click();
  const inspectorBox=await page.locator('.canvas-inspector').boundingBox();
  expect(inspectorBox.y+inspectorBox.height).toBeLessThanOrEqual(844);
  const lastCondition=page.locator('.canvas-inspector [data-live-input]').last();
  await lastCondition.scrollIntoViewIfNeeded();
  await lastCondition.click();
  expect(await lastCondition.evaluate(el=>{const r=el.getBoundingClientRect();return el.contains(document.elementFromPoint(r.x+r.width/2,r.y+r.height/2));})).toBe(true);
  await page.getByRole('button',{name:'收起侧栏',exact:true}).click();
  await page.getByRole('button',{name:'查看当前建议书'}).click();
  await expect(page.locator('#mission-note')).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
  await expect(page.locator('.mission-page')).not.toContainText(/Harness|modelCalls|执行记录/);
  await page.locator('.mission-shortlist [data-u-pane=canvas]').click();
  await expect(page.locator('.tree-origin')).toBeVisible();
});
